//! Text operations with the semantics of Swift's `String`, in which the Mac app's text rules are
//! written, so both apps split, compare and case text the same way.
//!
//! - A character is an extended grapheme cluster, as Swift's `Character` is; here it is the
//!   `&str` holding it. "e" followed by a combining acute accent is one character.
//! - A character's properties (letter, number, whitespace, punctuation) are its first scalar's,
//!   as `Character.isLetter` and the rest read them. Upper and lower case follow `Character`'s
//!   rules for characters of several scalars.
//! - Strings and characters are equal when they are canonically equivalent, as Swift's `==`,
//!   `Set` and `Dictionary` treat them: "é" written as one scalar equals "e" and U+0301. Keys of
//!   maps go through [`canonical_key`] for the same reason.
//! - Case mappings are Unicode's full mappings, scalar by scalar and without context, as
//!   `String.lowercased()` does: "ß" uppercases to "SS", and a final sigma is not special.
//! - Trimming works on scalars, with Foundation's character sets ([`CharacterSet`]).
//!
//! These were checked against the Swift runtime on macOS, scalar by scalar: white space,
//! punctuation, symbols, case properties and mappings, emoji properties and the grapheme breaks
//! of the golden inputs all match Rust's Unicode data. Where Swift differs, the scalars are
//! listed in `swift_string/tables.rs`, generated by `tools/swift-character-tables.swift`.

use std::borrow::Cow;
use std::ops::Range;

use unicode_normalization::{IsNormalized, UnicodeNormalization, is_nfc_quick};
use unicode_properties::{EmojiStatus, GeneralCategory, GeneralCategoryGroup, UnicodeEmoji, UnicodeGeneralCategory};
use unicode_segmentation::UnicodeSegmentation;

